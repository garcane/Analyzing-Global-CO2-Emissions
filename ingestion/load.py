"""Load a validated file into a Snowflake RAW table.

Design (see docs/decisions/adr-log.md):
- every source column lands as VARCHAR; typing happens in dbt staging;
- each load appends rows tagged with a `_LOAD_ID`; nothing is updated in place;
- META.INGESTION_LOG records every attempt; staging reads only the latest SUCCESS load
  (view META.LATEST_SUCCESSFUL_LOAD);
- the same file hash as the latest successful load is a no-op (idempotent);
- on any failure the rows of that load are deleted and the log row is marked FAILED.
"""

from __future__ import annotations

import logging
import uuid
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from ingestion.config import SnowflakeSettings
from ingestion.extract import FetchedFile, utcnow
from ingestion.sources import SourceSpec
from ingestion.validate import ValidationResult

log = logging.getLogger(__name__)

META_COLUMNS = [
    ("_LOAD_ID", "VARCHAR"),
    ("_SOURCE_FILE", "VARCHAR"),
    ("_FILE_SHA256", "VARCHAR"),
    ("_DOWNLOADED_AT_UTC", "TIMESTAMP_NTZ"),
    ("_LOADED_AT_UTC", "TIMESTAMP_NTZ"),
    ("_SOURCE_ROW_NUMBER", "NUMBER"),
]


class LoadError(RuntimeError):
    pass


@dataclass(frozen=True)
class LoadResult:
    status: str  # 'loaded' | 'skipped'
    load_id: str | None
    rows: int


def connect(settings: SnowflakeSettings):
    import snowflake.connector

    return snowflake.connector.connect(**settings.connection_params())


def _lit(value: str) -> str:
    """Quote a string literal for SQL (values here are generated by us, but escape anyway)."""
    return "'" + value.replace("'", "''") + "'"


def _ts(value: datetime) -> str:
    return _lit(value.strftime("%Y-%m-%d %H:%M:%S.%f")) + "::TIMESTAMP_NTZ"


def ensure_objects(cur: Any, db: str, spec: SourceSpec) -> None:
    # Schemas (RAW.META, RAW.EMBER, RAW.OWID) are created by infra/snowflake_setup.sql; the loader
    # role deliberately has no CREATE SCHEMA privilege.
    cur.execute(f"CREATE STAGE IF NOT EXISTS {db}.META.INGEST_STAGE")
    cur.execute(
        f"""CREATE TABLE IF NOT EXISTS {db}.META.INGESTION_LOG (
            LOAD_ID VARCHAR NOT NULL, SOURCE_NAME VARCHAR NOT NULL, TARGET_TABLE VARCHAR NOT NULL,
            SOURCE_URL VARCHAR, SOURCE_FILE VARCHAR, FILE_SHA256 VARCHAR NOT NULL, FILE_BYTES NUMBER,
            EXPECTED_ROWS NUMBER, LOADED_ROWS NUMBER, STATUS VARCHAR NOT NULL, ERROR_MESSAGE VARCHAR,
            DOWNLOADED_AT_UTC TIMESTAMP_NTZ, STARTED_AT_UTC TIMESTAMP_NTZ NOT NULL,
            FINISHED_AT_UTC TIMESTAMP_NTZ)"""
    )
    cur.execute(
        f"""CREATE VIEW IF NOT EXISTS {db}.META.LATEST_SUCCESSFUL_LOAD AS
            SELECT SOURCE_NAME, LOAD_ID, FILE_SHA256, FINISHED_AT_UTC FROM (
                SELECT *, ROW_NUMBER() OVER (PARTITION BY SOURCE_NAME ORDER BY FINISHED_AT_UTC DESC) AS RN
                FROM {db}.META.INGESTION_LOG WHERE STATUS = 'SUCCESS'
            ) WHERE RN = 1"""
    )
    cols = ", ".join(f"{c.upper()} VARCHAR" for c in spec.raw_columns)
    meta = ", ".join(f"{n} {t}" for n, t in META_COLUMNS)
    cur.execute(f"CREATE TABLE IF NOT EXISTS {db}.{spec.fqn} ({cols}, {meta})")


def latest_success_sha(cur: Any, db: str, source_name: str) -> str | None:
    cur.execute(
        f"SELECT FILE_SHA256 FROM {db}.META.LATEST_SUCCESSFUL_LOAD WHERE SOURCE_NAME = %s", (source_name,)
    )
    row = cur.fetchone()
    return row[0] if row else None


def copy_sql(db: str, spec: SourceSpec, fetched: FetchedFile, load_id: str, loaded_at: datetime) -> str:
    n = len(spec.raw_columns)
    targets = ", ".join([c.upper() for c in spec.raw_columns] + [n_ for n_, _ in META_COLUMNS])
    selects = ", ".join(
        [f"${i}" for i in range(1, n + 1)]
        + [
            _lit(load_id),
            _lit(fetched.path.name),
            _lit(fetched.sha256),
            _ts(fetched.downloaded_at_utc),
            _ts(loaded_at),
            "METADATA$FILE_ROW_NUMBER",
        ]
    )
    return f"""COPY INTO {db}.{spec.fqn} ({targets})
        FROM (SELECT {selects} FROM @{db}.META.INGEST_STAGE/{spec.name}/{load_id}/)
        FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('') ENCODING = 'UTF8')
        ON_ERROR = ABORT_STATEMENT"""


def load_file(
    conn: Any,
    db: str,
    spec: SourceSpec,
    fetched: FetchedFile,
    validation: ValidationResult,
) -> LoadResult:
    cur = conn.cursor()
    try:
        ensure_objects(cur, db, spec)

        if latest_success_sha(cur, db, spec.name) == fetched.sha256:
            log.info("%s: identical to the latest successful load, skipping", spec.name)
            return LoadResult("skipped", None, 0)

        load_id = uuid.uuid4().hex
        started = utcnow()
        cur.execute(
            f"""INSERT INTO {db}.META.INGESTION_LOG
                (LOAD_ID, SOURCE_NAME, TARGET_TABLE, SOURCE_URL, SOURCE_FILE, FILE_SHA256, FILE_BYTES,
                 EXPECTED_ROWS, STATUS, DOWNLOADED_AT_UTC, STARTED_AT_UTC)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, 'RUNNING', %s, %s)""",
            (load_id, spec.name, spec.fqn, fetched.source_url, fetched.path.name, fetched.sha256,
             fetched.size_bytes, validation.rows, fetched.downloaded_at_utc, started),
        )

        try:
            stage_path = f"@{db}.META.INGEST_STAGE/{spec.name}/{load_id}/"
            cur.execute(f"PUT 'file://{fetched.path.resolve().as_posix()}' {stage_path} "
                        "AUTO_COMPRESS = TRUE OVERWRITE = TRUE")
            cur.execute(copy_sql(db, spec, fetched, load_id, started))
            cur.execute(f"SELECT COUNT(*) FROM {db}.{spec.fqn} WHERE _LOAD_ID = %s", (load_id,))
            loaded = cur.fetchone()[0]
            if loaded != validation.rows:
                raise LoadError(f"Loaded {loaded} rows but the file has {validation.rows}")
        except Exception as exc:
            _mark_failed(cur, db, spec, load_id, str(exc))
            raise

        cur.execute(
            f"UPDATE {db}.META.INGESTION_LOG SET STATUS = 'SUCCESS', LOADED_ROWS = %s, "
            "FINISHED_AT_UTC = %s WHERE LOAD_ID = %s",
            (loaded, utcnow(), load_id),
        )
        cur.execute(f"REMOVE {stage_path}")
        return LoadResult("loaded", load_id, loaded)
    finally:
        cur.close()


def _mark_failed(cur: Any, db: str, spec: SourceSpec, load_id: str, message: str) -> None:
    """Best effort clean-up: a failed load's rows are removed and it is never the 'latest' load."""
    try:
        cur.execute(f"DELETE FROM {db}.{spec.fqn} WHERE _LOAD_ID = %s", (load_id,))
    except Exception:
        log.exception("could not delete rows of failed load %s", load_id)
    try:
        cur.execute(
            f"UPDATE {db}.META.INGESTION_LOG SET STATUS = 'FAILED', ERROR_MESSAGE = %s, "
            "FINISHED_AT_UTC = %s WHERE LOAD_ID = %s",
            (message[:2000], utcnow(), load_id),
        )
    except Exception:
        log.exception("could not mark load %s as FAILED", load_id)
