-- Global Energy Intelligence Pipeline: one-time Snowflake setup (v2).
-- Run manually, in a Snowflake workspace, as ACCOUNTADMIN. Review before running.
-- Nothing in this file is executed by the pipeline. It is safe to re-run (IF NOT EXISTS / idempotent grants).
--
-- v2 gives this project its OWN databases (GEI_RAW, GEI_ANALYTICS) so it is separate from tutorial or
-- course data in RAW / ANALYTICS, and revokes the broader v1 grants (section 5).
-- Placeholders for NEW service users only: <LOADER_PUBLIC_KEY>, <TRANSFORMER_PUBLIC_KEY>
-- (see docs/snowflake_setup.md). If the users already exist, section 6 leaves them unchanged.

----------------------------------------------------------------------
-- 1. Warehouse + credit cap (trial account: keep it small)
----------------------------------------------------------------------
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS GEI_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- CREDIT_QUOTA is a placeholder: set it to a share of your trial credits.
CREATE RESOURCE MONITOR IF NOT EXISTS GEI_MONITOR
  WITH CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE GEI_WH SET RESOURCE_MONITOR = GEI_MONITOR;

----------------------------------------------------------------------
-- 2. Roles (least privilege; none of them is an admin role)
----------------------------------------------------------------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS GEI_LOADER;       -- writes GEI_RAW
CREATE ROLE IF NOT EXISTS GEI_TRANSFORMER;  -- reads GEI_RAW, writes GEI_ANALYTICS (dbt)
CREATE ROLE IF NOT EXISTS GEI_REPORTER;     -- reads GEI_ANALYTICS.MARTS (Power BI, later the AI assistant)
GRANT ROLE GEI_LOADER, GEI_TRANSFORMER, GEI_REPORTER TO ROLE SYSADMIN;

----------------------------------------------------------------------
-- 3. Databases and schemas (dedicated to this project)
----------------------------------------------------------------------
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS GEI_RAW;
CREATE SCHEMA IF NOT EXISTS GEI_RAW.EMBER;
CREATE SCHEMA IF NOT EXISTS GEI_RAW.OWID;
CREATE SCHEMA IF NOT EXISTS GEI_RAW.META;

CREATE DATABASE IF NOT EXISTS GEI_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS GEI_ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS GEI_ANALYTICS.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS GEI_ANALYTICS.MARTS;

----------------------------------------------------------------------
-- 4. Grants (scoped to GEI_RAW / GEI_ANALYTICS only)
----------------------------------------------------------------------
USE ROLE SECURITYADMIN;

GRANT USAGE, OPERATE ON WAREHOUSE GEI_WH TO ROLE GEI_LOADER;
GRANT USAGE, OPERATE ON WAREHOUSE GEI_WH TO ROLE GEI_TRANSFORMER;
GRANT USAGE ON WAREHOUSE GEI_WH TO ROLE GEI_REPORTER;

-- Loader: creates and writes tables/stage/view in the GEI_RAW schemas.
GRANT USAGE ON DATABASE GEI_RAW TO ROLE GEI_LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE VIEW ON SCHEMA GEI_RAW.EMBER TO ROLE GEI_LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE VIEW ON SCHEMA GEI_RAW.OWID  TO ROLE GEI_LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE VIEW ON SCHEMA GEI_RAW.META  TO ROLE GEI_LOADER;

-- Transformer: read-only on GEI_RAW (existing + future objects), full control in GEI_ANALYTICS.
GRANT USAGE ON DATABASE GEI_RAW TO ROLE GEI_TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE GEI_RAW TO ROLE GEI_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE GEI_RAW TO ROLE GEI_TRANSFORMER;
GRANT SELECT ON ALL VIEWS  IN DATABASE GEI_RAW TO ROLE GEI_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GEI_RAW.EMBER TO ROLE GEI_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GEI_RAW.OWID  TO ROLE GEI_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GEI_RAW.META  TO ROLE GEI_TRANSFORMER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA GEI_RAW.META  TO ROLE GEI_TRANSFORMER;

GRANT USAGE ON DATABASE GEI_ANALYTICS TO ROLE GEI_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON ALL SCHEMAS IN DATABASE GEI_ANALYTICS TO ROLE GEI_TRANSFORMER;
-- dbt dev/CI schemas (dbt_<name>_staging, ...) are created inside GEI_ANALYTICS:
GRANT CREATE SCHEMA ON DATABASE GEI_ANALYTICS TO ROLE GEI_TRANSFORMER;

-- Reporter: marts only.
GRANT USAGE ON DATABASE GEI_ANALYTICS TO ROLE GEI_REPORTER;
GRANT USAGE ON SCHEMA GEI_ANALYTICS.MARTS TO ROLE GEI_REPORTER;
GRANT SELECT ON ALL TABLES IN SCHEMA GEI_ANALYTICS.MARTS TO ROLE GEI_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GEI_ANALYTICS.MARTS TO ROLE GEI_REPORTER;
GRANT SELECT ON ALL VIEWS IN SCHEMA GEI_ANALYTICS.MARTS TO ROLE GEI_REPORTER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA GEI_ANALYTICS.MARTS TO ROLE GEI_REPORTER;

----------------------------------------------------------------------
-- 5. Revoke the broader v1 grants on the shared RAW / ANALYTICS databases
--    (these covered tutorial schemas such as JAFFLE_SHOP, STRIPE, DBT_GARCANE).
--    Revoking a privilege that was never granted is harmless.
----------------------------------------------------------------------
USE ROLE SECURITYADMIN;

REVOKE SELECT ON ALL TABLES IN DATABASE RAW FROM ROLE GEI_TRANSFORMER;
REVOKE SELECT ON ALL VIEWS  IN DATABASE RAW FROM ROLE GEI_TRANSFORMER;
REVOKE SELECT ON FUTURE TABLES IN SCHEMA RAW.EMBER FROM ROLE GEI_TRANSFORMER;
REVOKE SELECT ON FUTURE TABLES IN SCHEMA RAW.OWID  FROM ROLE GEI_TRANSFORMER;
REVOKE SELECT ON FUTURE TABLES IN SCHEMA RAW.META  FROM ROLE GEI_TRANSFORMER;
REVOKE SELECT ON FUTURE VIEWS  IN SCHEMA RAW.META  FROM ROLE GEI_TRANSFORMER;
REVOKE USAGE ON ALL SCHEMAS IN DATABASE RAW FROM ROLE GEI_TRANSFORMER;
REVOKE USAGE ON DATABASE RAW FROM ROLE GEI_TRANSFORMER;
REVOKE USAGE, CREATE TABLE, CREATE VIEW ON ALL SCHEMAS IN DATABASE ANALYTICS FROM ROLE GEI_TRANSFORMER;
REVOKE CREATE SCHEMA ON DATABASE ANALYTICS FROM ROLE GEI_TRANSFORMER;
REVOKE USAGE ON DATABASE ANALYTICS FROM ROLE GEI_TRANSFORMER;

REVOKE USAGE, CREATE TABLE, CREATE STAGE, CREATE VIEW ON SCHEMA RAW.EMBER FROM ROLE GEI_LOADER;
REVOKE USAGE, CREATE TABLE, CREATE STAGE, CREATE VIEW ON SCHEMA RAW.OWID  FROM ROLE GEI_LOADER;
REVOKE USAGE, CREATE TABLE, CREATE STAGE, CREATE VIEW ON SCHEMA RAW.META  FROM ROLE GEI_LOADER;
REVOKE USAGE ON DATABASE RAW FROM ROLE GEI_LOADER;

REVOKE SELECT ON ALL TABLES IN SCHEMA ANALYTICS.MARTS FROM ROLE GEI_REPORTER;
REVOKE SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.MARTS FROM ROLE GEI_REPORTER;
REVOKE SELECT ON ALL VIEWS IN SCHEMA ANALYTICS.MARTS FROM ROLE GEI_REPORTER;
REVOKE SELECT ON FUTURE VIEWS IN SCHEMA ANALYTICS.MARTS FROM ROLE GEI_REPORTER;
REVOKE USAGE ON SCHEMA ANALYTICS.MARTS FROM ROLE GEI_REPORTER;
REVOKE USAGE ON DATABASE ANALYTICS FROM ROLE GEI_REPORTER;

-- NOT done here (your decision, after the reload into GEI_RAW is verified): removing the v1 objects.
--   DROP SCHEMA RAW.EMBER;  DROP SCHEMA RAW.OWID;  DROP SCHEMA RAW.META;
--   DROP SCHEMA ANALYTICS.STAGING;  DROP SCHEMA ANALYTICS.INTERMEDIATE;  DROP SCHEMA ANALYTICS.MARTS;
-- The tutorial schemas (JAFFLE_SHOP, STRIPE, PUBLIC, DBT_GARCANE) are never touched by this project.

----------------------------------------------------------------------
-- 6. Service users (key-pair auth, no password). No-op if they already exist.
----------------------------------------------------------------------
USE ROLE SECURITYADMIN;

CREATE USER IF NOT EXISTS GEI_LOADER_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = GEI_LOADER
  DEFAULT_WAREHOUSE = GEI_WH
  RSA_PUBLIC_KEY = '<LOADER_PUBLIC_KEY>';
GRANT ROLE GEI_LOADER TO USER GEI_LOADER_SVC;

CREATE USER IF NOT EXISTS GEI_TRANSFORMER_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = GEI_TRANSFORMER
  DEFAULT_WAREHOUSE = GEI_WH
  RSA_PUBLIC_KEY = '<TRANSFORMER_PUBLIC_KEY>';
GRANT ROLE GEI_TRANSFORMER TO USER GEI_TRANSFORMER_SVC;

